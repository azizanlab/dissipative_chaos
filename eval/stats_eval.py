    M = 16
    N_grid = 128
    L      = 100.0

    def reconstruct(traj):
        U = np.zeros((N_grid, T), dtype=complex)
        U[1:M+1,:] = traj[:,:M].T + 1j*traj[:,M:].T
        U[-M: ,:]  = np.conj(U[1:M+1,:][::-1,:])
        return sp_ifft(U, axis=0, norm='ortho').real

    u_true = reconstruct(true)
    u_pred = reconstruct(pred)
    u_hat = reconstruct(hat)

    t = np.arange(T)*dt
    x = np.linspace(0, L, N_grid, endpoint=False)

    threshold = np.inf

    def mask_after_blowup(field):
        exceed_time = (np.abs(field) > threshold).any(axis=0)
        if not exceed_time.any():
            return np.ma.array(field, mask=np.zeros_like(field, dtype=bool))
        first_idx = np.argmax(exceed_time)
        masked = field.copy()
        masked[:, first_idx:] = np.nan
        return np.ma.masked_invalid(masked)

    u_true_plot = mask_after_blowup(u_true)
    u_hat_plot = mask_after_blowup(u_hat)
