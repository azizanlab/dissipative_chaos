def evaluate_fourier_spectrum(gt_traj, star_traj, hat_traj, save_path=None):
    def get_power_spectrum(traj):
        fft_coeffs = np.fft.fft(traj, axis=0)
        power = np.abs(fft_coeffs)**2
        avg_power = np.mean(power, axis=1)
        return avg_power[:len(avg_power) // 2]

    def calculate_spectrum_error(spec_true, spec_pred, eps=1e-12):
        log_spec_true = np.log10(spec_true + eps)
        log_spec_pred = np.log10(spec_pred + eps)
        return np.mean((log_spec_true - log_spec_pred)**2)

    if gt_traj.ndim == 3:
        batch_size = gt_traj.shape[0]
        print(f"\n--- Performing Batched Fourier Evaluation ({batch_size} trajectories) ---")

        batch_errors_star = []
        batch_errors_hat = []

        all_spec_gt = []
        all_spec_star = []
        all_spec_hat = []

        for i in range(batch_size):
            gt_single = gt_traj[i]
            star_single = star_traj[i]
            hat_single = hat_traj[i]

            spec_gt = get_power_spectrum(gt_single)
            spec_star = get_power_spectrum(star_single)
            spec_hat = get_power_spectrum(hat_single)

            all_spec_gt.append(spec_gt)
            all_spec_star.append(spec_star)
            all_spec_hat.append(spec_hat)

            batch_errors_star.append(calculate_spectrum_error(spec_gt, spec_star))
            batch_errors_hat.append(calculate_spectrum_error(spec_gt, spec_hat))

        final_error_star = np.mean(batch_errors_star)
        final_error_hat = np.mean(batch_errors_hat)

        plot_spec_gt = np.mean(all_spec_gt, axis=0)
        plot_spec_star = np.mean(all_spec_star, axis=0)
        plot_spec_hat = np.mean(all_spec_hat, axis=0)

    elif gt_traj.ndim == 2:
        print("\n--- Performing Single Trajectory Fourier Evaluation ---")
        plot_spec_gt = get_power_spectrum(gt_traj)
        plot_spec_star = get_power_spectrum(star_traj)
        plot_spec_hat = get_power_spectrum(hat_traj)

        final_error_star = calculate_spectrum_error(plot_spec_gt, plot_spec_star)
        final_error_hat = calculate_spectrum_error(plot_spec_gt, plot_spec_hat)
    else:
        raise ValueError(f"Input trajectory has an unsupported shape: {gt_traj.shape}. Expected 2 or 3 dimensions.")

    print(f"Spectrum Difference (GT vs. f* Projected): {final_error_star:.6f}")
    print(f"Spectrum Difference (GT vs. f̂ No Projection): {final_error_hat:.6f}")
    print("---------------------------------")

    if save_path:
        plt.figure(figsize=(12, 7))
        modes = np.arange(len(plot_spec_gt))

        plt.plot(modes, plot_spec_gt, label='Ground Truth', color='black', linewidth=2.5, alpha=0.8)
        plt.plot(modes, plot_spec_star, label=r'$f^*$ With Projection', color='#1f77b4', linestyle='--')
        plt.plot(modes, plot_spec_hat, label=r'$\hat{f}$ Unconstrained', color='#d62728', linestyle=':')

        plt.yscale('log')
        plt.xlabel('Frequency Mode Index')
        plt.ylabel('Power (Log Scale)')
        plt.title('Fourier Power Spectrum Comparison')
        plt.legend()
        plt.grid(True, which="both", ls="--", alpha=0.6)
        plt.tight_layout()
        plt.savefig(save_path, dpi=300)
        plt.close()
        print(f"Saved Fourier spectrum plot to {save_path}")

    return final_error_star, final_error_hat



def Eval_all_traj(gt_traj, Star_traj, Hat_traj, Q, c, x_0, save_dir, idx=None, scatter_lim=None, hist_lim=None):
    if idx is not None:
        gt_flat = gt_traj[idx]
        Star_flat = Star_traj[idx]
        Hat_flat = Hat_traj[idx]
        
        # Find the length of the valid, non-NaN part of the unconstrained trajectory
        first_nan_idx = np.where(np.isnan(Hat_flat).any(axis=1))[0]
        
        if len(first_nan_idx) > 0:
            valid_length = first_nan_idx[0]
            print(f"\nUnstable trajectory detected. Truncating comparison to the first {valid_length} time steps.")
        else:
            valid_length = len(Hat_flat)
        # Create truncated versions of all trajectories for a fair comparison
        gt_truncated = gt_flat[:valid_length]
        star_truncated = Star_flat[:valid_length]
        hat_truncated = Hat_flat[:valid_length]
    else:
        gt_flat = gt_traj.reshape(-1, gt_traj.shape[-1])
        Star_flat = Star_traj.reshape(-1, Star_traj.shape[-1])
        Hat_flat = Hat_traj.reshape(-1, Hat_traj.shape[-1])

    Hat_flat = filter_nan_traj(Hat_flat)

    # Evaluate the Hat trajectory
    U, gt_pca, Star_pca, Hat_pca, pca = GT_based_PCA_eval(gt_flat, Star_flat, Hat_flat, PCA_n=2, save_path=os.path.join(save_dir, "fhat_PCA_scatter.png"), lim=np.array(scatter_lim))
    # Evaluate the Star trajectory
    plot_projected_point_cloud_bound(Q, c, x_0, pca, gt_pca, Star_pca, save_path=os.path.join(save_dir, "fstar_PCA_scatter.png"), lim=scatter_lim)

    KL_star, JS_star, KL_hat, JS_hat = pca_histogram_eval(gt_pca, Star_pca, Hat_pca, bins=80, lim=hist_lim, save_path=os.path.join(save_dir, "fstar_fhat_PCA_hist.png"), title_gt='Ground Truth', title_pred=r'$f^*$ With Projection', title_hat=r'$\hat{f}$ Unconstrained')
    print(fr"$f^*$ With Projection - KL Divergence: {KL_star}, Jensen-Shannon Divergence: {JS_star}")
    print(fr"$\hat{{f}}$ Unconstrained - KL Divergence: {KL_hat}, Jensen-Shannon Divergence: {JS_hat}")

    if idx is not None:
        evaluate_fourier_spectrum(
            gt_truncated,
            star_truncated,
            hat_truncated,
            save_path=os.path.join(save_dir, "fourier_spectrum.png")
        )
    else:
        evaluate_fourier_spectrum(
            gt_traj,
            Star_traj,
            Hat_traj,
            save_path=os.path.join(save_dir, "fourier_spectrum.png")
        )
