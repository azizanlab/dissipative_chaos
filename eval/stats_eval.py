def plot_projected_point_cloud_bound(Q, c, x0, pca, pca_gt_traj, pca_star_traj, save_path=None, lim=[[-40, 10], [-20, 30]]):
    print("Generating projected point cloud of the ellipsoid boundary...")
    D = Q.shape[0]
    
    if x0.ndim == 2:
        x0 = x0.flatten()

    num_points = int(5e5)
    z = np.random.randn(D, num_points)
    z /= np.linalg.norm(z, axis=0)

    try:
        Q_inv_sqrt = np.linalg.inv(sqrtm(Q))
    except np.linalg.LinAlgError:
        print("Warning: The learned matrix Q is singular. Using pseudo-inverse.")
        Q_inv_sqrt = np.linalg.pinv(sqrtm(Q))
        
    ellipsoid_surface_pts = x0[:, np.newaxis] + Q_inv_sqrt @ z * np.sqrt(c)

    projected_boundary_pts = pca.transform(ellipsoid_surface_pts.T)

    # --- Plotting ---
    fig, ax = plt.subplots(figsize=(10, 10))

    ax.scatter(projected_boundary_pts[:, 0], projected_boundary_pts[:, 1], s=1, c='red', alpha=0.2, label='Ellipsoid', zorder=1)

    ax.scatter(pca_gt_traj[:, 0], pca_gt_traj[:, 1], s=5, alpha=0.5, label="Ground Truth", zorder=2)
    ax.scatter(pca_star_traj[:, 0], pca_star_traj[:, 1], s=5, alpha=0.5, label=r"Prediction $f^*$", zorder=3)

    ax.set_xlim(lim[0])
    ax.set_ylim(lim[1])

    ax.set_xlabel('PC 1')
    ax.set_ylabel('PC 2')
    ax.set_title(r'With Projection $f^*$')
    ax.legend()

    if save_path:
        plt.savefig(save_path, dpi=300)
        print(f"Saved plot to {save_path}")

    plt.close(fig)
    
