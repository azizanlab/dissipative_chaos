# color bar helpers: cmap for within the v-range, progressively darkened colors towards black outside the v-range.
def _apply_cmap_with_darkening(Z, vmin, vmax, *, cmap='seismic', vcenter=0.0, gamma=0.8, bad_color=(1, 1, 1, 1)):
    Z = np.array(Z, copy=False)

    if np.ma.isMaskedArray(Z):
        mask = np.isnan(Z.filled(np.nan)) | Z.mask
        Z_plain = Z.filled(np.nan)
    else:
        mask = np.isnan(Z)
        Z_plain = Z

    if vcenter is None:
        norm = colors.Normalize(vmin=vmin, vmax=vmax)
    else:
        norm = colors.TwoSlopeNorm(vmin=vmin, vcenter=vcenter, vmax=vmax)

    base_cmap = cmap if isinstance(cmap, colors.Colormap) else plt.get_cmap(cmap)

    Z_clipped = np.clip(Z_plain, vmin, vmax)
    base_rgba = base_cmap(norm(Z_clipped)).astype(float)  # (..., 4)

    factor = np.ones_like(Z_plain, dtype=float)
    eps = 1e-12

    pos_over = Z_plain > vmax
    if np.any(pos_over):
        factor[pos_over] = (vmax / (np.abs(Z_plain[pos_over]) + eps)) ** gamma

    neg_over = Z_plain < vmin
    if np.any(neg_over):
        factor[neg_over] = (np.abs(vmin) / (np.abs(Z_plain[neg_over]) + eps)) ** gamma

    base_rgba[..., :3] *= factor[..., None]
    base_rgba[..., :3] = np.clip(base_rgba[..., :3], 0.0, 1.0)

    if np.any(mask):
        base_rgba[mask] = bad_color

    return base_rgba, norm, base_cmap


def imshow_with_darkening(ax, Z, *, vmin, vmax, cmap='seismic', vcenter=0.0, gamma=0.8, bad_color=(1, 1, 1, 1), **imshow_kwargs):
    for k in ('cmap', 'norm', 'vmin', 'vmax', 'bad_color'):
        imshow_kwargs.pop(k, None)

    rgba, norm, base_cmap = _apply_cmap_with_darkening(
        Z, vmin, vmax, cmap=cmap, vcenter=vcenter, gamma=gamma, bad_color=bad_color
    )
    im = ax.imshow(rgba, **imshow_kwargs)
    sm = plt.cm.ScalarMappable(norm=norm, cmap=base_cmap)
    sm.set_array([])
    return im, sm



def load_L96_traj(data_loc):
    def _pickle_load_cpu(path):
        restore = torch.serialization.default_restore_location

        def cpu_restore(storage, location):
            cpu_location = torch.device('cpu') if isinstance(location, torch.device) else 'cpu'
            return restore(storage, cpu_location)

        with open(path, 'rb') as f:
            original_restore = torch.serialization.default_restore_location
            torch.serialization.default_restore_location = cpu_restore
            try:
                return pickle.load(f)
            finally:
                torch.serialization.default_restore_location = original_restore

    try:
        test_results = torch.load(data_loc, map_location=torch.device('cpu'))
    except Exception:
        test_results = _pickle_load_cpu(data_loc)

    GT_traj = test_results['Test_trajs']['GT'].detach().cpu().numpy()
    Star_traj = test_results['Test_trajs']['traj_1'].detach().cpu().numpy()
    Hat_traj = test_results['Test_trajs']['traj_2'].detach().cpu().numpy()

    return GT_traj, Star_traj, Hat_traj

def load_L96_model_Q(model_loc):
    state_dict = torch.load(model_loc, map_location=torch.device('cpu'))

    L = state_dict['V.L']
    c_tensor = state_dict['c']
    x_0_tensor = state_dict['V.x_0']

    L = torch.tril(L)
    L.diagonal().exp_()

    Q = L @ L.t()

    Q_np = Q.detach().numpy()
    c_np = (c_tensor**2).detach().numpy()
    x_0_np = x_0_tensor.detach().numpy()

    return Q_np, c_np, x_0_np


